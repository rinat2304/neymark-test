INSERT INTO trip_stops (
    trip_id,
    stop_id,
    stop_order,
    arrival_at,
    departure_at
)
SELECT
    t.id,
    rs.stop_id,
    rs.stop_order,
    CASE
        WHEN rs.stop_order = 1 THEN NULL
        ELSE DATE_ADD(
            t.departure_at,
            INTERVAL ((rs.stop_order - 1) * 120) MINUTE
        )
    END AS arrival_at,
    CASE
        WHEN rs.stop_order = 1 THEN t.departure_at
        ELSE DATE_ADD(
            t.departure_at,
            INTERVAL (((rs.stop_order - 1) * 120) + 15) MINUTE
        )
    END AS departure_at
FROM trips t
JOIN route_stops rs
    ON rs.route_id = t.route_id;